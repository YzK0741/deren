        f"clustered_lights = {str(cfg['clustered_lights']).lower()}",
        f"ssao = {str(cfg['ssao']).lower()}",
        f"ssao_radius = {cfg['ssao_radius']}",
        f"ssao_intensity = {cfg['ssao_intensity']}",
